
package tugasprak;


public class Tugas5Soal7 {
    public static void main(String[] args) {
         int i = 0;
        System.out.println("Contoh i++:");
        while (i < 5) {
            System.out.println(i++); // nilai ditampilkan dulu baru ditambah
        }

        int j = 0;
        System.out.println("\nContoh ++i:");
        while (j < 5){
            System.out.println(++j);
        }

    }
}
